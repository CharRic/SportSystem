const assert = require("assert");
const fs = require("fs");
const path = require("path");
const { digest, coachActive } = require("../cloudfunctions/clubApi/coach-binding-service");

const root = path.resolve(__dirname, "..");
const read = (file) => fs.readFileSync(path.join(root, file), "utf8");
const cloud = read("cloudfunctions/clubApi/v2.js");
const binding = read("cloudfunctions/clubApi/coach-binding-service.js");
const coachService = read("cloudfunctions/clubApi/coach-service.js");
const coachWork = read("cloudfunctions/clubApi/coach-work-service.js");
const auth = read("miniprogram/pages/auth/index.wxml");
const bindJs = read("miniprogram/pages/coach-bind/index.js");
const bindWxml = read("miniprogram/pages/coach-bind/index.wxml");
const team = read("miniprogram/pages/coach-team/index.wxml");
const form = read("miniprogram/pages/coach-profile-form/index.wxml");
let checks = 0;
const check = (value, message) => { assert(value, message); checks += 1; };

check(binding.includes('requireRole(user, ["admin"])') && binding.includes('"createCoachInvite"'), "ADMIN creates coach invite");
check(binding.includes("非ADMIN") || binding.match(/createInvite[\s\S]*requireRole\(user, \["admin"\]\)/), "non-admin invite creation is blocked");
check(binding.includes("coachId: state.coachId") && binding.includes("coachProfileId: profile._id"), "invite is profile-bound");
check(binding.includes('scene = `ci_${token}`') && !binding.includes("role=COACH"), "QR carries an opaque scene token");
check(binding.includes('code = `NL${secureText(4)}`') && /^NL[A-Z0-9]{4}$/.test("NL8K2P"), "six-character backup code exists");
check(bindJs.includes('api.call("getCoachInvitePreview"') && bindWxml.includes("preview.coach.name"), "QR preview reads server coach data");
check(bindJs.includes("this.data.code") && bindJs.includes("getCoachInvitePreview"), "backup code uses same preview API");
check(bindWxml.includes("确认绑定") && binding.includes("if (!input.confirmed)"), "preview does not auto-bind");
check(binding.includes('role: "coach"') && binding.includes('roles: ["coach"]'), "confirmed account receives COACH role");
check(binding.includes("coachId: state.coachId") && binding.includes("boundUserId: state.coachId"), "coachId is linked on both sides");
check(binding.includes('status: "USED"') && binding.includes("usedByUserId"), "invite becomes USED");
check(binding.includes('invite.status === "USED"'), "USED invite cannot be reused");
check(binding.includes("Number(invite.expiresAt || 0) <= Date.now()") && binding.includes('status: "EXPIRED"'), "expired invite is rejected");
check(binding.includes('invite.status === "CANCELLED"'), "cancelled invite is rejected");
check(binding.includes("if (state.bound)") && binding.includes("已经完成绑定"), "bound coach cannot bind twice");
check(binding.includes('currentUser.role === "parent"') && binding.includes("不能") || binding.includes("家长账号"), "PARENT cannot be overwritten");
check(binding.includes('currentUser.role === "admin"') && binding.includes("管理员身份"), "ADMIN cannot be overwritten");
check(cloud.includes("assertCoachAccess") && cloud.includes("requireRole(user, roles)"), "forged frontend role cannot grant COACH access");
check(binding.includes('"unbindCoachAccount"') && form.includes("解除微信绑定"), "ADMIN can unbind");
check(binding.includes("historyDeleted: false") && binding.includes("历史课程、评价、比赛和教练档案不会删除"), "unbind preserves history");
check(binding.includes('role: "unregistered"') && binding.includes('status: "DISABLED"'), "old WeChat loses coach access");
check(binding.includes("if (!state.bound)") && binding.includes('status: "ACTIVE"'), "unbound active coach can receive another invite");
check(binding.includes("coachUserId: state.coachId") && coachService.includes("coachUserId"), "new WeChat reuses stable coachId");
check(!coachActive({ active: false, status: "ACTIVE" }) && binding.includes("不能生成绑定邀请"), "INACTIVE coach cannot create invite");
check(binding.includes("COACH_INACTIVE") && binding.includes("当前教练账号已停用"), "INACTIVE coach cannot log in");
check(binding.includes('"REACTIVATE_COACH"') && binding.includes('status: active ? "ACTIVE"'), "restored coach returns ACTIVE");
check(coachWork.includes('fetchAll("coachProfiles")') && coachWork.includes("coachUserId || row._id"), "unbound coach can be scheduled before binding");
check(coachService.includes("publicView") && !binding.includes("remove coachProfiles"), "coach biography survives binding");
check(binding.includes("assignedClassIds") && coachWork.includes("plannedCoachAssignments"), "existing timetable follows stable coachId");
check(!binding.includes('collection("feedback").remove') && !binding.includes('collection("playerAssessments").remove') && !binding.includes('collection("matches").remove'), "growth assessment and league data are unaffected");

check(auth.includes("教练员绑定") && team.includes("已绑定") && team.includes("未绑定") && form.includes("邀请教练绑定"), "binding UI is registered across welcome and admin pages");
check(digest("NL8K2P") === digest("NL8K2P") && digest("NL8K2P") !== digest("NL8K2Q"), "credentials are stored as one-way hashes");
assert.strictEqual(checks, 32);
console.log(`Coach binding regression: ${checks} checks passed`);
